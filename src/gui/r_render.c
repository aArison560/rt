static SDL_Texture *font_texture;
static SDL_Renderer *sdl_renderer;
static int font_atlas_w;
static int font_atlas_h;

static int text_width_fn(mu_Font font, const char *str, int len) {
  (void)font;
  if (len < 0) len = (int)strlen(str);
  return len * FONT_W;
}

static int text_height_fn(mu_Font font) {
  (void)font;
  return FONT_H;
}

static void create_font_texture(void) {
  int num_chars = FONT_LAST - FONT_FIRST + 1;
  font_atlas_w = num_chars * FONT_W;
  font_atlas_h = FONT_H;

  SDL_Surface *surface = SDL_CreateRGBSurfaceWithFormat(0, font_atlas_w, font_atlas_h, 32, SDL_PIXELFORMAT_RGBA32);
  if (!surface) return;

  SDL_LockSurface(surface);
  memset(surface->pixels, 0, surface->h * surface->pitch);

  for (int ch = 0; ch < num_chars; ch++) {
    const unsigned char *glyph = font_data[ch];
    for (int y = 0; y < FONT_H; y++) {
      unsigned char row = glyph[y];
      for (int x = 0; x < FONT_W; x++) {
        if (row & (128 >> x)) {
          int px = ch * FONT_W + x;
          Uint32 *pixels = (Uint32 *)((char *)surface->pixels + y * surface->pitch);
          pixels[px] = 0xFFFFFFFF;
        }
      }
    }
  }
  SDL_UnlockSurface(surface);

  font_texture = SDL_CreateTextureFromSurface(sdl_renderer, surface);
  SDL_FreeSurface(surface);

  if (font_texture) {
    SDL_SetTextureBlendMode(font_texture, SDL_BLENDMODE_BLEND);
  }
}

static void draw_icon(int icon_id, mu_Rect rect, mu_Color color) {
  /* Simple icon rendering using rectangles */
  SDL_SetRenderDrawBlendMode(sdl_renderer, SDL_BLENDMODE_BLEND);

  int cx = rect.x + rect.w / 2;
  int cy = rect.y + rect.h / 2;
  int s = mu_min(rect.w, rect.h) / 4;

  switch (icon_id) {
    case MU_ICON_CLOSE: {
      /* X shape */
      SDL_SetRenderDrawColor(sdl_renderer, color.r, color.g, color.b, color.a);
      for (int i = -s; i <= s; i++) {
        SDL_Rect r1 = {cx + i - 1, cy + i - 1, 2, 2};
        SDL_RenderFillRect(sdl_renderer, &r1);
        SDL_Rect r2 = {cx + i - 1, cy - i - 1, 2, 2};
        SDL_RenderFillRect(sdl_renderer, &r2);
      }
      break;
    }
    case MU_ICON_CHECK: {
      /* Checkmark */
      SDL_SetRenderDrawColor(sdl_renderer, color.r, color.g, color.b, color.a);
      int x0 = rect.x + s;
      int y0 = cy;
      int x1 = cx - 1;
      int y1 = cy + s;
      int x2 = rect.x + rect.w - s;
      int y2 = cy - s;
      /* Draw 3 line segments */
      for (int i = 0; i < s * 2; i++) {
        float t = (float)i / (float)(s * 2);
        int px, py;
        px = x0 + (int)(t * (x1 - x0));
        py = y0 + (int)(t * (y1 - y0));
        SDL_Rect r = {px, py, 2, 2};
        SDL_RenderFillRect(sdl_renderer, &r);
      }
      for (int i = 0; i < s * 2; i++) {
        float t = (float)i / (float)(s * 2);
        int px, py;
        px = x1 + (int)(t * (x2 - x1));
        py = y1 + (int)(t * (y2 - y1));
        SDL_Rect r = {px, py, 2, 2};
        SDL_RenderFillRect(sdl_renderer, &r);
      }
      break;
    }
    case MU_ICON_COLLAPSED: {
      /* Right-pointing triangle */
      SDL_SetRenderDrawColor(sdl_renderer, color.r, color.g, color.b, color.a);
      for (int row = 0; row < s * 2; row++) {
        int width = row + 1;
        int startX = cx - s / 2;
        int startY = cy - s + row;
        SDL_Rect r = {startX, startY, width > 0 ? width : 1, 1};
        SDL_RenderFillRect(sdl_renderer, &r);
      }
      break;
    }
    case MU_ICON_EXPANDED: {
      /* Down-pointing triangle */
      SDL_SetRenderDrawColor(sdl_renderer, color.r, color.g, color.b, color.a);
      for (int row = 0; row < s * 2; row++) {
        int width = s * 2 - row;
        int startX = cx - s;
        int startY = cy - s / 2 + row;
        SDL_Rect r = {startX, startY, width > 0 ? width : 1, 1};
        SDL_RenderFillRect(sdl_renderer, &r);
      }
      break;
    }
    default:
      break;
  }
}

int r_init(mu_Context *ctx, SDL_Renderer *renderer) {
  sdl_renderer = renderer;
  font_texture = NULL;

  ctx->text_width = text_width_fn;
  ctx->text_height = text_height_fn;

  create_font_texture();
  return font_texture != NULL;
}

void r_render(mu_Context *ctx, SDL_Renderer *renderer) {
  mu_Command *cmd = NULL;

  while (mu_next_command(ctx, &cmd)) {
    switch (cmd->type) {
      case MU_COMMAND_CLIP: {
        SDL_Rect rc = {
          cmd->clip.rect.x, cmd->clip.rect.y,
          cmd->clip.rect.w, cmd->clip.rect.h
        };
        SDL_RenderSetClipRect(renderer, &rc);
        break;
      }
      case MU_COMMAND_RECT: {
        mu_Rect r = cmd->rect.rect;
        mu_Color c = cmd->rect.color;
        SDL_SetRenderDrawBlendMode(renderer, SDL_BLENDMODE_BLEND);
        SDL_SetRenderDrawColor(renderer, c.r, c.g, c.b, c.a);
        SDL_Rect rc = {r.x, r.y, r.w, r.h};
        SDL_RenderFillRect(renderer, &rc);
        break;
      }
      case MU_COMMAND_TEXT: {
        mu_TextCommand *tc = &cmd->text;
        const char *str = tc->str;
        int len = (int)strlen(str);
        if (len <= 0) break;

        mu_Color c = tc->color;
        SDL_SetTextureColorMod(font_texture, c.r, c.g, c.b);

        int x = tc->pos.x;
        int y = tc->pos.y;

        for (int i = 0; i < len; i++) {
          unsigned char ch = (unsigned char)str[i];
          if (ch < FONT_FIRST || ch > FONT_LAST) continue;

          int char_idx = ch - FONT_FIRST;
          SDL_Rect src = {char_idx * FONT_W, 0, FONT_W, FONT_H};
          SDL_Rect dst = {x + i * FONT_W, y, FONT_W, FONT_H};
          SDL_RenderCopy(renderer, font_texture, &src, &dst);
        }
        break;
      }
      case MU_COMMAND_ICON: {
        draw_icon(cmd->icon.id, cmd->icon.rect, cmd->icon.color);
        break;
      }
      default:
        break;
    }
  }
  SDL_RenderSetClipRect(renderer, NULL);
}
